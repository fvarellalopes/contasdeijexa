import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const c={window:{}};
vm.runInNewContext(readFileSync('dist/assets/products.js','utf8'),c);
const p=c.window.CATALOG_PRODUCTS.find(p=>p.code==='BLX-IEM-001');
assert(p);
const originalPrice=p.price;
const files=['214908','214937','214948','215007'];
const folder=`dist/assets/products/${p.slug}`;
mkdirSync(folder,{recursive:true});
const mapping=files.map((time,i)=>{
 const source=`image(20261021-${time}).png`;
 const from='/workspace/scratch/2f60f8e06fc6/upload/'+source;
 const image=`/assets/products/${p.slug}/${i===0?'capa':'foto-'+(i+1)}.png`;
 copyFileSync(from,'dist'+image);
 const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
 assert.equal(hash(from),hash('dist'+image));
 return {source,image,sha256:hash(from)};
});
p.name='Brajá Luxo Iemanjá (Rosa Branca)';
p.cover=mapping[0].image;
p.images=mapping.map(m=>m.image);
p.alt='Brajá Luxo Iemanjá com rosa branca, contas azuis e brancas e pingente de espelho';
p.photoStatus='Foto fornecida';
p.highlights='Rosa branca · Contas azuis · Espelho';
p.finishes='Rosa branca central e pingente de espelho com pedra azul facetada, acabamento em metal e pequenos pingentes de peixe e estrela-do-mar.';
p.story[2]='No centro, uma rosa branca conduz ao pingente de espelho com pedra azul facetada e moldura em metal. Pequenos pingentes de peixe e estrela-do-mar completam o acabamento.';
assert.equal(p.price,originalPrice);
writeFileSync('dist/assets/products.js','window.CATALOG_PRODUCTS = '+JSON.stringify(c.window.CATALOG_PRODUCTS,null,2)+';\n');
writeFileSync('data/photo-iemanja-rosa-branca.json',JSON.stringify({sku:p.code,price:p.price,photos:mapping},null,2)+'\n');
console.log(p.name,p.price,': quatro fotos originais.');
